import { expect, test } from '@playwright/test'
import { resolve } from 'node:path'
import { pathToFileURL } from 'node:url'

const appUrl = process.env.LUSTRA_E2E_FILE_MODE === '1' ? pathToFileURL(resolve('dist/index.html')).href : '/'

test('Alt reveals targeted reset buttons and blur reset is undoable', async ({ page }) => {
  await page.goto(appUrl)
  await page.getByRole('button', { name: /import photos/i }).click()
  await page.locator('input[type=file]').first().setInputFiles([resolve('src-tauri/tests/fixtures/test_exif_01.jpg')])
  await page.getByRole('button', { name: /import 1 photo/i }).click()
  await expect(page.locator('.preview-board')).toBeVisible()
  const frameSection = page.getByRole('button', { name: 'Frame', exact: true })
  if (await frameSection.getAttribute('aria-expanded') !== 'true') await frameSection.click()
  await page.getByRole('button', { name: 'Blurred', exact: true }).click()
  const appearance = page.getByRole('button', { name: 'Appearance', exact: true })
  if (await appearance.getAttribute('aria-expanded') !== 'true') await appearance.click()
  const blur = page.getByRole('spinbutton', { name: 'Blur strength' })
  await blur.fill('30')
  await blur.press('Enter')
  const reset = page.locator('button[aria-label="Reset Blur strength"]')
  await expect(reset).toBeDisabled()
  await page.keyboard.down('Alt')
  const row = page.locator('.slider-field__label-row').filter({ hasText: 'Blur strength' })
  await row.hover()
  await expect(reset).toBeEnabled()
  await reset.click()
  await expect(blur).toHaveValue('18')
  await page.keyboard.up('Alt')
  await expect(reset).toBeDisabled()
  await page.getByRole('button', { name: 'Undo' }).click()
  await expect(blur).toHaveValue('30')

  await page.getByRole('button', { name: 'This Photo' }).click()
  await blur.fill('12')
  await blur.press('Enter')
  await page.keyboard.down('Alt')
  await row.hover()
  await reset.click()
  await expect(blur).toHaveValue('30')
  await page.keyboard.up('Alt')
  await page.getByRole('button', { name: 'Undo' }).click()
  await expect(blur).toHaveValue('12')
  await page.getByRole('button', { name: 'Redo' }).click()
  await expect(blur).toHaveValue('30')
  await page.getByRole('button', { name: /All Photos/ }).click()
  await blur.fill('24')
  await blur.press('Enter')
  await page.getByRole('button', { name: 'This Photo' }).click()
  await expect(blur).toHaveValue('24')

  await page.getByRole('button', { name: /All Photos/ }).click()
  const top = page.getByRole('spinbutton', { name: 'Top' })
  const bottom = page.getByRole('spinbutton', { name: 'Bottom' })
  await top.fill('18')
  await top.press('Enter')
  await bottom.fill('20')
  await bottom.press('Enter')
  await expect(top).toHaveValue('18')
  await expect(bottom).toHaveValue('20')
  const paddingHeading = page.locator('.inspector-section__heading').filter({ has: page.getByRole('button', { name: 'Padding', exact: true }) })
  await page.keyboard.down('Alt')
  await paddingHeading.hover()
  const resetPadding = page.getByRole('button', { name: 'Reset Padding' })
  await resetPadding.click()
  await expect(top).toHaveValue('8')
  await expect(bottom).toHaveValue('15')
  await page.keyboard.up('Alt')
  await page.getByRole('button', { name: 'Undo' }).click()
  await expect(top).toHaveValue('18')
  await expect(bottom).toHaveValue('20')

  await page.getByRole('button', { name: 'Fine inner border' }).click()
  await page.getByRole('button', { name: 'Soft shadow' }).click()
  const appearanceHeading = page.locator('.inspector-section__heading').filter({ has: appearance })
  await page.keyboard.down('Alt')
  await appearanceHeading.hover()
  await page.getByRole('button', { name: 'Reset Appearance', exact: true }).click()
  await expect(blur).toHaveValue('18')
  await expect(page.getByRole('button', { name: 'Fine inner border' })).toHaveAttribute('aria-pressed', 'false')
  await expect(page.getByRole('button', { name: 'Soft shadow' })).toHaveAttribute('aria-pressed', 'false')
  await page.keyboard.up('Alt')
  await page.getByRole('button', { name: 'Undo' }).click()
  await expect(blur).toHaveValue('24')
  await expect(page.getByRole('button', { name: 'Fine inner border' })).toHaveAttribute('aria-pressed', 'true')
  await expect(page.getByRole('button', { name: 'Soft shadow' })).toHaveAttribute('aria-pressed', 'true')

  await page.getByRole('button', { name: 'This Photo' }).click()
  await top.fill('17')
  await top.press('Enter')
  await bottom.fill('22')
  await bottom.press('Enter')
  await page.getByRole('button', { name: 'Fine inner border' }).click()
  await page.keyboard.down('Alt')
  await paddingHeading.hover()
  await resetPadding.click()
  await expect(top).toHaveValue('18')
  await expect(bottom).toHaveValue('20')
  await expect(page.getByRole('button', { name: 'Fine inner border' })).toHaveAttribute('aria-pressed', 'false')
  await page.keyboard.up('Alt')
  await page.getByRole('button', { name: 'Undo' }).click()
  await expect(top).toHaveValue('17')
  await expect(bottom).toHaveValue('22')
  await expect(page.getByRole('button', { name: 'Fine inner border' })).toHaveAttribute('aria-pressed', 'false')
  await page.getByRole('button', { name: 'Redo' }).click()
  await expect(top).toHaveValue('18')
  await expect(bottom).toHaveValue('20')
  await expect(page.getByRole('button', { name: 'Fine inner border' })).toHaveAttribute('aria-pressed', 'false')
})
