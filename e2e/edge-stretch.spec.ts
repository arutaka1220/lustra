import { expect, test } from '@playwright/test'
import { resolve } from 'node:path'
import { pathToFileURL } from 'node:url'

const appUrl = process.env.LUSTRA_E2E_FILE_MODE === '1' ? pathToFileURL(resolve('dist/index.html')).href : '/'

test('Edge Stretch modes and independent background controls update a real photo preview', async ({ page }) => {
  await page.goto(appUrl)
  await page.getByRole('button', { name: /import photos/i }).click()
  await page.locator('input[type=file]').first().setInputFiles([resolve(process.env.LUSTRA_EDGE_STRETCH_PHOTO ?? 'src-tauri/tests/fixtures/test_exif_01.jpg')])
  const details = page.getByRole('dialog', { name: /photo details in png and webp/i })
  if (await details.isVisible()) await details.getByRole('button', { name: 'Got It' }).click()
  await page.getByRole('button', { name: /import 1 photo/i }).click()
  await expect(page.getByRole('region', { name: /photos/i })).toBeVisible({ timeout: 10_000 })
  const edgeTile = page.getByRole('button', { name: /edge stretch/i })
  const thumbnail = edgeTile.locator('.style-preview--edgeStretch')
  await expect(thumbnail).toBeVisible()
  expect((await thumbnail.boundingBox())?.height).toBe(42)
  await thumbnail.screenshot({ path: '/tmp/lustra-edge-stretch-thumbnail.png' })
  await edgeTile.focus()
  await page.keyboard.press('Enter')
  await expect(edgeTile).toHaveAttribute('aria-pressed', 'true')
  await page.getByRole('button', { name: /appearance/i }).click()
  const preview = page.locator('.framed-preview-surface')
  await expect(preview).toBeVisible()
  await expect(page.getByLabel('Stretch Mode')).toHaveValue('extend')
  const extended = await preview.screenshot()
  await page.getByLabel('Stretch Mode').selectOption('mirror')
  const mirrored = await preview.screenshot()
  expect(Buffer.compare(extended, mirrored)).not.toBe(0)
  await page.getByLabel('Stretch Mode').selectOption('extend')
  await page.getByRole('spinbutton', { name: 'Blur' }).fill('0')
  await page.getByRole('spinbutton', { name: 'Blur' }).press('Enter')
  const sharp = await preview.screenshot()
  await page.getByRole('spinbutton', { name: 'Blur' }).fill('28')
  await page.getByRole('spinbutton', { name: 'Blur' }).press('Enter')
  const blurred = await preview.screenshot()
  expect(Buffer.compare(sharp, blurred)).not.toBe(0)
  await page.getByRole('spinbutton', { name: 'Blur' }).fill('0')
  await page.getByRole('spinbutton', { name: 'Blur' }).press('Enter')
  await page.getByRole('spinbutton', { name: 'Fade' }).fill('0')
  await page.getByRole('spinbutton', { name: 'Fade' }).press('Enter')
  const noFade = await preview.screenshot()
  await page.getByRole('spinbutton', { name: 'Fade' }).fill('35')
  await page.getByRole('spinbutton', { name: 'Fade' }).press('Enter')
  await expect(page.getByRole('spinbutton', { name: 'Fade' })).toHaveValue('35')
  const fade = await preview.screenshot()
  expect(Buffer.compare(noFade, fade)).not.toBe(0)
  await page.getByRole('textbox', { name: 'Preset name' }).fill('Edge preset')
  await page.getByRole('button', { name: 'Save preset' }).click()
  await page.getByRole('button', { name: 'Black', exact: true }).click()
  await page.getByLabel('Saved frame presets').selectOption('Edge preset')
  await expect(page.getByRole('button', { name: /edge stretch/i })).toHaveAttribute('aria-pressed', 'true')
  await expect(page.getByLabel('Stretch Mode')).toHaveValue('extend')
  await expect(page.getByRole('spinbutton', { name: 'Fade' })).toHaveValue('35')
})
