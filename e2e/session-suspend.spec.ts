import { expect, test } from '@playwright/test'
import { resolve } from 'node:path'

test('Lustra home suspends edits and a new import starts an independent session', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: /import photos/i }).click()
  await page.locator('input[type=file]').first().setInputFiles(resolve('src-tauri/tests/fixtures/test_exif_01.jpg'))
  await page.getByRole('button', { name: /import 1 photo/i }).click()
  await expect(page.getByRole('region', { name: /photos/i })).toBeVisible()
  const top = page.getByRole('spinbutton', { name: 'Top' })
  await top.fill('19')
  await top.press('Enter')
  await page.getByRole('button', { name: 'This Photo' }).click()
  await top.fill('15')
  await top.press('Enter')
  await page.keyboard.down('Alt')
  await page.locator('.slider-field__label-row').filter({ hasText: 'Top' }).hover()
  await page.getByRole('button', { name: 'Reset Top' }).click()
  await expect(top).toHaveValue('19')
  await page.keyboard.up('Alt')
  await page.getByRole('button', { name: /lustra home/i }).click()
  await expect(page.getByRole('heading', { name: /suspended sessions/i })).toBeVisible()
  await page.getByRole('button', { name: /resume test_exif_01\.jpg/i }).click()
  await expect(page.getByRole('region', { name: /photos/i })).toBeVisible()
  const resumedTop = page.getByRole('spinbutton', { name: 'Top' })
  await expect(resumedTop).toHaveValue('19')
  await page.getByRole('button', { name: /all photos/i }).click()
  await resumedTop.fill('21')
  await resumedTop.press('Enter')
  await page.getByRole('button', { name: 'This Photo' }).click()
  await expect(resumedTop).toHaveValue('21')

  await page.getByRole('button', { name: /lustra home/i }).click()
  await page.getByRole('button', { name: /import photos/i }).click()
  await page.locator('input[type=file]').first().setInputFiles(resolve('src-tauri/tests/fixtures/test_exif_01.jpg'))
  await page.getByRole('button', { name: /import 1 photo/i }).click()
  await expect(page.getByRole('region', { name: /photos/i })).toBeVisible()
  await expect(page.getByRole('spinbutton', { name: 'Top' })).toHaveValue('8')
  await page.getByRole('button', { name: /lustra home/i }).click()
  await expect(page.getByRole('heading', { name: /suspended sessions/i })).toBeVisible()
})
