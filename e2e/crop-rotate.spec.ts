import { expect, test } from '@playwright/test'
import { resolve } from 'node:path'
import { pathToFileURL } from 'node:url'

const appUrl = process.env.LUSTRA_E2E_FILE_MODE === '1' ? pathToFileURL(resolve('dist/index.html')).href : '/'

test('crop mode supports handle edits, ratios, numeric rotation, commit, and cancel', async ({ page }) => {
  await page.setViewportSize({ width: 960, height: 760 })
  await page.goto(appUrl)
  await page.getByRole('button', { name: /import photos/i }).click()
  await page.locator('input[type=file]').first().setInputFiles([resolve('src-tauri/tests/fixtures/test_exif_01.jpg')])
  const details = page.getByRole('dialog', { name: /photo details in png and webp/i })
  if (await details.isVisible()) await details.getByRole('button', { name: 'Got It' }).click()
  await page.getByRole('button', { name: /import 1 photo/i }).click()
  await expect(page.locator('.preview-board')).toBeVisible()

  await page.locator('.preview-board').dblclick()
  const overlay = page.locator('.crop-overlay')
  await expect(overlay).toBeVisible()
  const panel = page.locator('.crop-controls')
  await expect(panel).toBeVisible()
  await expect(page.locator('.crop-settings')).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Frame', exact: true })).toBeHidden()
  await expect(page.getByRole('heading', { name: 'Crop & Rotate' })).toBeVisible()
  const panelBox = await panel.boundingBox()
  const ratioSelect = page.getByRole('combobox', { name: 'Aspect Ratio' })
  const ratioBox = await ratioSelect.boundingBox()
  expect(ratioBox!.x).toBeGreaterThanOrEqual(panelBox!.x)
  expect(ratioBox!.x + ratioBox!.width).toBeLessThanOrEqual(panelBox!.x + panelBox!.width + 1)
  const corner = page.locator('.crop-handle--se')
  await corner.hover()
  await expect(overlay).toHaveClass(/is-hover-resize-corner/)
  const box = await corner.boundingBox()
  await page.mouse.move(box!.x + box!.width / 2, box!.y + box!.height / 2)
  await page.mouse.down()
  await page.mouse.move(box!.x + box!.width / 2 - 45, box!.y + box!.height / 2 - 32)
  await page.mouse.up()
  const cropBox = await page.locator('.crop-outline').boundingBox()
  const rotateHit = page.locator('.crop-rotate-hit').last()
  await rotateHit.hover()
  await expect(overlay).toHaveClass(/is-hover-rotate/)
  await page.mouse.move(cropBox!.x + cropBox!.width + 22, cropBox!.y + cropBox!.height + 22)
  await page.mouse.down()
  await page.mouse.move(cropBox!.x + cropBox!.width + 34, cropBox!.y + cropBox!.height + 10)
  await page.mouse.up()
  expect(await page.evaluate(() => document.documentElement.dataset.lustraPreviewDrag)).toBeUndefined()
  const rotation = page.getByRole('textbox', { name: 'Rotation' })
  const rotationValue = page.getByRole('status', { name: 'Rotation angle' })
  await expect(rotationValue).not.toHaveText('0.00°')
  await page.getByRole('button', { name: 'Reset rotation' }).click()
  await expect(rotation).toHaveValue('0.00')
  await expect(rotationValue).toHaveText('0.00°')
  await rotation.fill('-')
  await expect(rotation).toHaveValue('-')
  await rotation.fill('-4.')
  await expect(rotation).toHaveValue('-4.')
  await rotation.fill('-4.49')
  await expect(rotation).toHaveValue('-4.49')
  await expect(rotationValue).toHaveText('-4.49°')
  await rotation.press('Enter')
  await expect(rotation).toHaveValue('-4.49')
  await rotation.fill('12.345')
  await expect(rotationValue).toHaveText('12.35°')
  await rotation.press('Enter')
  await expect(rotationValue).toHaveText('12.35°')
  await page.getByRole('combobox', { name: 'Aspect Ratio' }).selectOption('custom')
  await page.getByRole('spinbutton', { name: 'Custom ratio' }).fill('1.25')
  await expect(page.getByRole('spinbutton', { name: 'Custom ratio' })).toHaveValue('1.25')
  const lock = page.getByRole('checkbox', { name: 'Lock ratio' })
  await expect(lock).toBeChecked()
  await lock.uncheck()
  await expect(lock).not.toBeChecked()
  await lock.check()
  await page.getByRole('combobox', { name: 'Aspect Ratio' }).selectOption('4:3')
  await rotation.fill('12.75')
  await rotation.press('Enter')
  await expect(rotation).toHaveValue('12.75')
  await page.getByRole('textbox', { name: 'Preset name' }).fill('Portrait crop')
  await page.getByRole('button', { name: 'Save preset' }).click()
  await page.getByRole('button', { name: 'Update preset' }).click()
  await page.getByRole('combobox', { name: 'Crop presets' }).selectOption('')
  await page.getByRole('combobox', { name: 'Aspect Ratio' }).selectOption('free')
  await page.getByRole('combobox', { name: 'Crop presets' }).selectOption('Portrait crop')
  await expect(page.getByRole('combobox', { name: 'Aspect Ratio' })).toHaveValue('4:3')
  await page.getByRole('textbox', { name: 'Preset name' }).fill('Portrait cropc')
  await page.keyboard.press('c')
  await expect(overlay).toBeVisible()
  await page.keyboard.press('Enter')
  await expect(overlay).toBeHidden()
  await expect(page.getByRole('button', { name: 'Frame', exact: true })).toBeVisible()
  await page.keyboard.press('c')
  await expect(overlay).toBeVisible()
  await page.locator('.preview-board').dblclick({ position: { x: 300, y: 220 } })
  await expect(overlay).toBeHidden()
  await page.keyboard.press('c')
  await expect(overlay).toBeVisible()
  await rotation.fill('-20.5')
  await rotation.press('Enter')
  await page.getByRole('button', { name: 'Cancel' }).click()
  await expect(overlay).toBeHidden()
  await expect(page.getByRole('button', { name: 'Frame', exact: true })).toBeVisible()
  await page.keyboard.press('c')
  await expect(overlay).toBeVisible()
  await page.getByRole('button', { name: 'Apply' }).click()
  await expect(overlay).toBeHidden()
  await page.keyboard.press('c')
  await expect(overlay).toBeVisible()
  await rotation.fill('33')
  await rotation.press('Enter')
  await page.keyboard.press('Escape')
  await expect(overlay).toBeHidden()
})
