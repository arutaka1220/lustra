import { expect, test } from '@playwright/test'
import { resolve } from 'node:path'
import { pathToFileURL } from 'node:url'

const appUrl = process.env.LUSTRA_E2E_FILE_MODE === '1' ? pathToFileURL(resolve('dist/index.html')).href : '/'

test('Portrait Card keeps its canvas and photo settings separate from Standard', async ({ page }) => {
  await page.setViewportSize({ width: 1024, height: 780 })
  await page.goto(appUrl)
  await page.getByRole('button', { name: /import photos/i }).click()
  await page.locator('input[type=file]').first().setInputFiles([resolve('src-tauri/tests/fixtures/test_exif_01.jpg')])
  const details = page.getByRole('dialog', { name: /photo details/i })
  if (await details.isVisible()) await details.getByRole('button', { name: /got it/i }).click()
  await page.getByRole('button', { name: /import 1 photo/i }).click()
  await expect(page.locator('.preview-board')).toBeVisible()

  const frameSection = page.getByRole('button', { name: 'Frame', exact: true })
  if (await frameSection.getAttribute('aria-expanded') !== 'true') await frameSection.click()
  await page.getByRole('button', { name: 'Blur', exact: true }).click()
  const appearance = page.getByRole('button', { name: 'Appearance' })
  if (await appearance.getAttribute('aria-expanded') !== 'true') await appearance.click()
  const standardBlur = page.getByRole('spinbutton', { name: 'Blur strength' })
  await standardBlur.fill('25')
  await standardBlur.press('Enter')

  const layout = page.getByRole('combobox', { name: 'Canvas layout' })
  await layout.click()
  await page.getByRole('option', { name: 'Portrait Card' }).click()
  const ratio = page.getByRole('combobox', { name: 'Canvas ratio' })
  await expect(ratio).toHaveText('4:5')
  const layoutBox = await layout.boundingBox()
  const ratioBox = await ratio.boundingBox()
  expect(layoutBox).not.toBeNull()
  expect(ratioBox).not.toBeNull()
  expect(ratioBox!.y).toBeGreaterThan(layoutBox!.y + layoutBox!.height)
  expect(Math.abs(layoutBox!.width - ratioBox!.width)).toBeLessThan(2)
  await expect.poll(() => page.locator('.portrait-canvas-field > span').evaluateAll(labels => labels.every(label => label.scrollWidth <= label.clientWidth))).toBe(true)
  const size = page.getByRole('spinbutton', { name: 'Photo Size' })
  await size.fill('65')
  await size.press('Enter')
  const position = page.getByRole('spinbutton', { name: 'Vertical Position' })
  await position.fill('0.2')
  await position.press('Enter')
  await page.keyboard.down('Alt')
  await page.locator('.slider-field__label-row').filter({ hasText: 'Photo size' }).hover()
  await page.getByRole('button', { name: 'Reset Photo size' }).click()
  await expect(size).toHaveValue('80')
  await page.keyboard.up('Alt')
  const backgroundBlur = page.getByRole('spinbutton', { name: 'Background Blur' })
  const backgroundBrightness = page.getByRole('spinbutton', { name: 'Background Brightness' })
  await expect(backgroundBlur).toHaveValue('32')
  await expect(backgroundBrightness).toHaveValue('90')
  await expect(size).toBeVisible()
  const appearanceContent = page.locator('.inspector-section').filter({ has: appearance }).locator('.inspector-section__content')
  const appearanceOrder = await appearanceContent.evaluate(element => Array.from(element.querySelectorAll('.slider-field__label, .portrait-reset-position')).map(control => control.textContent?.trim()))
  expect(appearanceOrder.slice(0, 5)).toEqual(['Photo size', 'Vertical position', 'Reset position', 'Background blur', 'Background brightness'])
  await page.getByRole('button', { name: 'Ambient Gradient' }).click()
  await expect(page.getByRole('spinbutton', { name: 'Background Blur' })).toHaveCount(0)
  await expect(page.getByRole('spinbutton', { name: 'Intensity' })).toBeVisible()
  await page.getByRole('button', { name: 'Blur' }).click()
  await expect(page.getByRole('spinbutton', { name: 'Background Blur' })).toHaveValue('32')
  await page.locator('.preview-board').click()
  await page.keyboard.press('c')
  await expect(page.locator('.crop-overlay')).toBeVisible()
  await page.getByRole('button', { name: 'Apply' }).click()
  await expect(page.locator('.crop-overlay')).toBeHidden()
  await page.getByRole('button', { name: 'Reset Position' }).click()
  await expect(position).toHaveValue('0')
  const dragBoard = await page.locator('.preview-board').boundingBox()
  if (!dragBoard) throw new Error('Could not measure the Portrait Card canvas')
  const dragX = dragBoard.x + dragBoard.width / 2
  const dragY = dragBoard.y + dragBoard.height / 2
  await page.mouse.move(dragX, dragY)
  await page.mouse.down()
  await page.mouse.move(dragX + 55, dragY)
  await page.mouse.up()
  await expect(position).toHaveValue('0')
  await page.mouse.move(dragX, dragY)
  await page.mouse.down()
  await page.mouse.move(dragX + 55, dragY + 25, { steps: 4 })
  await page.mouse.up()
  await expect.poll(async () => Number(await position.inputValue())).toBeGreaterThan(0)
  await position.fill('-0.15')
  await position.press('Enter')

  const board = page.locator('.preview-board')
  const rect = await board.boundingBox()
  expect(rect).not.toBeNull()
  expect(rect!.width / rect!.height).toBeCloseTo(0.8, 1)
  await layout.click()
  await page.getByRole('option', { name: 'Standard' }).click()
  await expect(page.getByRole('spinbutton', { name: 'Photo Size' })).toHaveCount(0)
  await page.getByRole('button', { name: 'Blur' }).click()
  await expect(page.getByRole('spinbutton', { name: 'Blur strength' })).toBeVisible()
  await expect(standardBlur).toHaveValue('25')
  await expect(page.getByRole('spinbutton', { name: 'Background Blur' })).toHaveCount(0)
  await layout.click()
  await page.getByRole('option', { name: 'Portrait Card' }).click()
  await expect(page.getByRole('spinbutton', { name: 'Background Blur' })).toHaveValue('32')
  await expect(size).toHaveValue('80')
  await expect(position).toHaveValue('-0.15')

  await ratio.click()
  await page.getByRole('option', { name: '1:1' }).click()
  const canvasHeading = page.locator('.inspector-section__heading').filter({ has: page.getByRole('button', { name: 'Canvas', exact: true }) })
  await page.keyboard.down('Alt')
  await canvasHeading.hover()
  await page.getByRole('button', { name: 'Reset Canvas', exact: true }).click()
  await page.keyboard.up('Alt')
  await expect(layout).toHaveText('Standard')
  await page.getByRole('button', { name: 'Undo' }).click()
  await expect(layout).toHaveText('Portrait Card')
  await expect(ratio).toHaveText('1:1')
  await expect(size).toHaveValue('80')
  await expect(position).toHaveValue('-0.15')

  await size.fill('65')
  await size.press('Enter')
  await position.fill('0.2')
  await position.press('Enter')
  const appearanceHeading = page.locator('.inspector-section__heading').filter({ has: page.getByRole('button', { name: 'Appearance', exact: true }) })
  await page.keyboard.down('Alt')
  await appearanceHeading.hover()
  await page.getByRole('button', { name: 'Reset Appearance', exact: true }).click()
  await page.keyboard.up('Alt')
  await expect(ratio).toHaveText('1:1')
  await expect(size).toHaveValue('80')
  await expect(position).toHaveValue('0')
  await page.getByRole('button', { name: 'Undo' }).click()
  await expect(ratio).toHaveText('1:1')
  await expect(size).toHaveValue('65')
  await expect(position).toHaveValue('0.2')
  await layout.click()
  await page.getByRole('option', { name: 'Standard' }).click()
  await expect(standardBlur).toHaveValue('25')
})
